def _get_company_domain(company: Company) -> str:
    """Extract company domain from company data."""
    comp = company.get("company") or {}
    return comp.get("domain", "company.com")


def _get_company_short_name(company: Company) -> str:
    """Extract a short company name for URLs."""
    comp = company.get("company") or {}
    name = comp.get("name", "company")
    # Convert "NexusTech Global" → "nexustech"
    return name.lower().replace(" ", "").replace("_", "")


def _transform_path(canonical: str, system: str, company: Company) -> str:
    """Transform canonical path to realistic system-specific URL/UNC path.

    Canonical paths look like: /departments/sales/Report.xlsx
    """
    short_name = _get_company_short_name(company)
    domain = _get_company_domain(company)

    # Parse canonical path
    parts = canonical.strip("/").split("/")
    # Expected: departments/<dept>/<filename> or similar
    if len(parts) >= 3 and parts[0].lower() == "departments":
        dept = parts[1]
        rest = "/".join(parts[2:])
    elif len(parts) >= 2:
        dept = parts[0]
        rest = "/".join(parts[1:])
    else:
        dept = "General"
        rest = parts[-1] if parts else "file"

    # Capitalize department for display
    dept_display = dept.replace("_", " ").title()

    if system == "microsoft_sharepoint":
        return f"https://{short_name}.sharepoint.com/sites/{dept_display}/Shared Documents/{rest}"
    elif system == "google_drive":
        return f"https://drive.google.com/corp/{dept_display}/{rest}"
    elif system == "document_repository":
        return f"\\\\docrepo\\{dept_display}\\{rest.replace('/', chr(92))}"
    elif system == "wiki":
        return f"https://wiki.{domain}/{dept_display}/{rest.replace(' ', '_')}"
    else:  # fileshare
        return f"\\\\fileserver01\\{dept_display}\\{rest.replace('/', chr(92))}"


