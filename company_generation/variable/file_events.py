"""
Session-based file event generator with Markov action transitions,
system/label-conditioned distributions, and cross-user consistency.

Events are generated in sessions (bursts of activity within a short time window)
rather than as independent random events. Each session follows a Markov chain
for action selection, with transition probabilities conditioned on the storage
system and file label. Deleted files are tracked globally to prevent future
access, and share events generate pending read tasks for cross-user fulfillment.
"""
from __future__ import annotations

