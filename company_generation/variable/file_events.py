def _generate_external_email(rng: random.Random) -> str:
    """Generate a fake external partner/vendor email."""
    first = rng.choice(_EXTERNAL_FIRST_NAMES)
    last = rng.choice(_EXTERNAL_LAST_NAMES)
    domain = rng.choice(_EXTERNAL_DOMAINS)
    return f"{first}.{last}@{domain}"


def _select_share_recipients(
    person: Person,
    people: List[Person],
    department_members: Dict[str, List[Person]],
    rng: random.Random,
) -> Tuple[List[str], List[str], bool]:
    """Select share recipients and return (display_emails, recipient_ids, has_external).

    Recipient count: 1 (70%), 2-5 (25%), group/6+ (4.5%), external (0.5%).
    Department distribution: 60% same, 30% adjacent, 10% random.
    """
    # Determine count bucket
    bucket = rng.choices(
        ["single", "small", "group", "external"],
        weights=[0.70, 0.25, 0.045, 0.005],
        k=1,
    )[0]

    if bucket == "external":
        ext_email = _generate_external_email(rng)
        return [ext_email], [], True

    if bucket == "single":
        count = 1
    elif bucket == "small":
        count = rng.randint(2, 5)
    else:  # group
        count = rng.randint(6, 12)

    person_id = person.get("id")
    dept_key = (person.get("department") or "").strip().lower()
    same_dept = [
        p for p in department_members.get(dept_key, [])
        if p.get("id") and p.get("id") != person_id
    ]
    other_people = [p for p in people if p.get("id") and p.get("id") != person_id]

    selected: List[Person] = []
    for _ in range(count):
        if not other_people:
            break
        # 60% same dept, 30% adjacent (random from others), 10% fully random
        r = rng.random()
        if r < 0.60 and same_dept:
            candidate = rng.choice(same_dept)
        elif r < 0.90 and other_people:
            candidate = rng.choice(other_people)
        elif other_people:
            candidate = rng.choice(other_people)
        else:
            break
        if candidate not in selected:
            selected.append(candidate)

    emails = []
    ids = []
    for p in selected:
        email = _primary_email(p) or p.get("id", "")
        emails.append(email)
        pid = p.get("id")
        if pid:
            ids.append(pid)

    return emails, ids, False


def _granted_via_for_system(system: str, rng: random.Random) -> str:
    """Return a realistic granted_via value conditioned on the storage system."""
    if system == "microsoft_sharepoint":
        return rng.choices(
            ["direct_share", "sharepoint_link", "teams_channel"],
            weights=[0.50, 0.35, 0.15],
            k=1,
        )[0]
    elif system == "google_drive":
        return rng.choices(
            ["direct_share", "link_sharing", "google_groups"],
            weights=[0.45, 0.40, 0.15],
            k=1,
        )[0]
    elif system == "wiki":
        return "page_permission"
    elif system == "document_repository":
        return rng.choices(
            ["folder_permission", "direct_share"],
            weights=[0.60, 0.40],
            k=1,
        )[0]
    else:  # fileshare
        return rng.choices(
            ["folder_permission", "network_share", "direct_share"],
            weights=[0.40, 0.35, 0.25],
            k=1,
        )[0]


