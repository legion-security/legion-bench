_SYSTEM_ACTION_WEIGHTS: Dict[str, Dict[str, float]] = {
    "microsoft_sharepoint": {"read": 0.700, "modify": 0.250, "share": 0.020, "delete": 0.003},
    "google_drive":         {"read": 0.650, "modify": 0.280, "share": 0.040, "delete": 0.003},
    "document_repository":  {"read": 0.800, "modify": 0.150, "share": 0.010, "delete": 0.005},
    "wiki":                 {"read": 0.750, "modify": 0.220, "share": 0.005, "delete": 0.002},
    "fileshare":            {"read": 0.720, "modify": 0.230, "share": 0.015, "delete": 0.005},
}

# Label-based multipliers applied to base weights (Business files suppress share/delete)
_LABEL_WEIGHT_MULTIPLIERS: Dict[str, Dict[str, float]] = {
    "Business": {"share": 0.3, "delete": 0.2},
    "Regular":  {},
}

# Markov transition matrix: given previous action, probabilities for next action
# Tuned so that the stationary distribution approximately matches
# the marginal action weights (~65% read, ~25% modify, ~3% share, ~0.5% delete).
_MARKOV_TRANSITIONS: Dict[str, Dict[str, float]] = {
    "read":   {"read": 0.68, "modify": 0.27, "share": 0.02, "delete": 0.003},
    "modify": {"read": 0.50, "modify": 0.43, "share": 0.03, "delete": 0.005},
    "share":  {"read": 0.60, "modify": 0.30, "share": 0.04, "delete": 0.003},
    # delete ends the session — no transitions
}

# Session size distribution weights (1-20 files per session, heavy-tailed)
_SESSION_SIZE_WEIGHTS = [1.0 / ((i + 1) ** 1.5) for i in range(20)]

# External partner domains for rare external share events
_EXTERNAL_DOMAINS = [
    "acme-consulting.com", "globaltech.io", "partner-services.net",
    "external-audit.com", "vendorlink.co", "advisory-group.org",
    "techpartners.com", "strategyworks.io", "compliance-experts.net",
    "outsource-solutions.com",
]

_EXTERNAL_FIRST_NAMES = [
    "j", "m", "a", "s", "d", "r", "l", "k", "t", "c",
    "n", "p", "b", "e", "h", "g", "w", "f", "v", "i",
]

_EXTERNAL_LAST_NAMES = [
    "smith", "jones", "williams", "brown", "taylor", "davies",
    "wilson", "evans", "thomas", "johnson", "roberts", "walker",
    "wright", "robinson", "thompson", "white", "hughes", "edwards",
    "green", "hall", "lewis", "harris", "clark", "patel", "jackson",
]

# Departments considered "high-business-file" (30-60% business files)
_HIGH_BUSINESS_DEPTS = {"finance", "legal", "hr", "human resources", "compliance", "accounting"}
# "Low-business-file" departments (5-20% business files)
_LOW_BUSINESS_DEPTS = {"engineering", "it", "development", "devops", "research"}


