def generate_file_event_logs(
    company: Company,
    *,
    seed: int = 1337,
    max_shares_per_file: int = 3,
    replace_existing: bool = True,
    events_multiplier: float = 1.0,
    baseline_std_scale: float = 1.0,
    generation_config: Optional[Dict[str, Any]] = None,
    burst_schedule: Optional[BurstSchedule] = None,
) -> Tuple[Dict[str, int], FileWorldState]:
    """
    Generate session-based file events for each person in the company.

    Events are organized into sessions (bursts of activity) with Markov
    action transitions, system-conditioned weights, and cross-user consistency.
    Canonical paths from company_files.json are transformed to realistic
    SharePoint URLs / UNC paths.

    Returns:
        A tuple of (stats_dict, world_state). The world_state contains
        pending share-read tasks for cross-user fulfillment.
    """
    from .constants_loader import load_company_files
    people, container_kind = _select_people_container(company)
    files = load_company_files(_get_company_id(company))
    max_shares_per_file = max(0, int(max_shares_per_file))
    stats: Dict[str, int] = {
        "files_total": len(files),
        "employees_total": len(people),
        "employees_with_events": 0,
        "events_requested": 0,
        "events_added": 0,
        "share_events": 0,
        "delete_events": 0,
        "unique_files_used": 0,
        "sessions_generated": 0,
    }
    gen_cfg = generation_config or company.get("_generation_config") or {}
    world_state = FileWorldState()

    if not people or not files or events_multiplier == 0:
        return stats, world_state

    # Build department index
    department_members: Dict[str, List[Person]] = defaultdict(list)
    for p in people:
        dept_key = (p.get("department") or "").strip().lower()
        if dept_key:
            department_members[dept_key].append(p)

    # Pre-compute window
    window_start = window_end = None
    if gen_cfg:
        window_start, window_end = get_window(gen_cfg)
    if not window_start or not window_end:
        window_end = datetime.now(timezone.utc)
        window_start = window_end - timedelta(days=30)

    base_weights = _long_tail_weights(len(files))
    files_used: Set[str] = set()
    base_seed = seed or 0

    requested_total = 0
    for idx_person, person in enumerate(people):
        person_id = person.get("id")
        if not person_id:
            continue
        ra = person.setdefault("recent_activity", {})
        if replace_existing:
            ra.pop("file_events", None)

        rng = random.Random(base_seed * 1009 + idx_person)

        # Resolve event count from baselines, scaled by multiplier
        if gen_cfg:
            target_events = resolve_event_count(
                person, "file", _DEFAULT_FILE_EVENTS, rng,
                scale_factor=events_multiplier,
                baseline_std_scale=baseline_std_scale,
            )
        else:
            target_events = max(0, round(vary_count(_DEFAULT_FILE_EVENTS, rng) * events_multiplier))

        if not replace_existing:
            existing_events = ra.get("file_events")
            existing_count = len(existing_events) if isinstance(existing_events, list) else 0
            target_events = max(target_events - existing_count, 0)

        if target_events <= 0:
            continue

        # Apply burst scaling
        if burst_schedule and burst_schedule.bursts:
            target_events = apply_burst_to_count(
                target_events, person_id, "file_events",
                burst_schedule, rng, window_start, window_end,
            )

        if target_events <= 0:
            continue

        # Build temporal samplers
        circadian = weekly = None
        if gen_cfg:
            circadian, weekly = resolve_person_temporal(person, gen_cfg)

        # Read baseline action weights
        baselines = person.get("behavior_baselines") or {}
        file_bl = baselines.get("file_baseline") or {}
        baseline_action_weights = file_bl.get("action_weights")

        # Compute label-conditioned file weights for this person
        person_dept = person.get("department") or ""
        file_weights = _compute_file_weights(files, base_weights, person_dept)

        requested_total += target_events

        # Distribute events into sessions
        session_sizes = _distribute_events_to_sessions(target_events, rng)
        events_for_person = 0

        for session_size in session_sizes:
            if events_for_person >= target_events:
                break

            # Pick session start time
            session_start = _sample_session_start(
                rng, circadian, weekly, window_start, window_end,
            )
            current_ts = session_start
            prev_action: Optional[str] = None
            stats["sessions_generated"] += 1

            for evt_idx in range(session_size):
                if events_for_person >= target_events:
                    break

                # Select a file (with label conditioning)
                file_meta = rng.choices(files, weights=file_weights, k=1)[0]
                canonical_path = file_meta.get("path")
                if not canonical_path:
                    continue

                system = _infer_system(canonical_path)
                label = (file_meta.get("type") or "regular").capitalize()
                allow_share = max_shares_per_file > 0
                allow_delete = True

                # Skip if file was already deleted
                if world_state.is_deleted(canonical_path, current_ts):
                    continue

                # Action selection: marginal for first event, Markov for subsequent
                if prev_action is None or evt_idx == 0:
                    action = _pick_marginal_action(
                        rng, system, label, allow_share, allow_delete,
                        baseline_action_weights,
                    )
                else:
                    next_action = _pick_markov_action(
                        rng, prev_action, system, label, allow_share, allow_delete,
                    )
                    if next_action is None:
                        break  # Session ends
                    action = next_action

                # Transform path to realistic format
                transformed_path = _transform_path(canonical_path, system, company)

                # Build event
                event: Dict[str, Any] = {
                    "ts": format_ts(current_ts) if gen_cfg else _format_ts(current_ts),
                    "action": action,
                    "path": transformed_path,
                    "system": system,
                    "label": label,
                    "owner_role": file_meta.get("owner role"),
                    "category": file_meta.get("type"),
                    "description": file_meta.get("content"),
                }

                # Handle share events
                if action == "share":
                    recipient_emails, recipient_ids, is_external = _select_share_recipients(
                        person, people, department_members, rng,
                    )
                    if not recipient_emails:
                        event["action"] = "modify"
                        action = "modify"
                    else:
                        granted_via = _granted_via_for_system(system, rng)
                        event["shared_with"] = recipient_emails
                        event["granted_via"] = granted_via
                        stats["share_events"] += 1

                        # Register share-read task (only for internal recipients)
                        if recipient_ids and not is_external:
                            task = ShareReadTask(
                                path=canonical_path,
                                transformed_path=transformed_path,
                                system=system,
                                label=label,
                                category=file_meta.get("type"),
                                description=file_meta.get("content"),
                                owner_role=file_meta.get("owner role"),
                                sharer_id=person_id,
                                sharer_email=_primary_email(person),
                                recipient_ids=recipient_ids,
                                share_ts=current_ts,
                                granted_via=granted_via,
                            )
                            world_state.register_share(task)

                # Handle delete events
                if action == "delete":
                    world_state.register_delete(canonical_path, current_ts)
                    stats["delete_events"] += 1

                # Add event to person's activity
                add_file_event_logs(
                    company,
                    **_event_target_kwargs(container_kind, person_id),
                    log=event,
                )
                files_used.add(canonical_path)
                stats["events_added"] += 1
                events_for_person += 1
                prev_action = action

                # Session ends after delete
                if action == "delete":
                    break

                # Advance timestamp within session (log-normal gap)
                gap_seconds = _sample_log_normal_gap(rng)
                current_ts = current_ts + timedelta(seconds=gap_seconds)

        if events_for_person:
            stats["employees_with_events"] += 1

    stats["unique_files_used"] = len(files_used)
    stats["events_requested"] = requested_total
    return stats, world_state
