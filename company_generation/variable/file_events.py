def _sample_log_normal_gap(rng: random.Random, mu: float = 4.0, sigma: float = 1.0) -> float:
    """Sample an intra-session time gap in seconds from a log-normal distribution.

    Default parameters: median ~55s, typical range 12s-6min.
    mu=4.0, sigma=1.0 → median=e^4≈55s, 68% in [20s, 148s].
    """
    return math.exp(rng.gauss(mu, sigma))


def _distribute_events_to_sessions(
    target_events: int,
    rng: random.Random,
) -> List[int]:
    """Distribute total events into sessions with heavy-tailed sizes.

    Returns a list of session sizes summing to approximately target_events.
    """
    if target_events <= 0:
        return []

    sessions: List[int] = []
    remaining = target_events

    while remaining > 0:
        # Sample session size (1-20, heavy-tailed toward small)
        max_size = min(20, remaining)
        if max_size <= 1:
            sessions.append(remaining)
            break
        size_weights = _SESSION_SIZE_WEIGHTS[:max_size]
        size = rng.choices(range(1, max_size + 1), weights=size_weights, k=1)[0]
        size = min(size, remaining)
        sessions.append(size)
        remaining -= size

    return sessions


def _sample_session_start(
    rng: random.Random,
    circadian,
    weekly,
    window_start: datetime,
    window_end: datetime,
) -> datetime:
    """Sample a session start time using the circadian/weekly model."""
    if circadian and weekly:
        return sample_timestamp(circadian, weekly, rng, window_start, window_end)

    # Fallback: pick a random business-hours timestamp
    span_days = max(1, (window_end - window_start).days)
    day_offset = rng.randint(0, span_days - 1)
    day = window_start + timedelta(days=day_offset)
    # Session start clusters
    cluster = rng.choices(
        [(8, 10.5), (13, 14.5), (16, 17.5)],
        weights=[0.45, 0.30, 0.25],
        k=1,
    )[0]
    hour_float = rng.uniform(cluster[0], cluster[1])
    hour = int(hour_float)
    minute = int((hour_float - hour) * 60)
    return day.replace(
        hour=hour % 24, minute=minute,
        second=rng.randint(0, 59), microsecond=0,
        tzinfo=timezone.utc,
    )


