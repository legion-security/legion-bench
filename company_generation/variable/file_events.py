def _get_action_weights(
    system: str,
    label: str,
    allow_share: bool,
    allow_delete: bool,
) -> Tuple[List[str], List[float]]:
    """Get action weights conditioned on system and label."""
    base = _SYSTEM_ACTION_WEIGHTS.get(system, _SYSTEM_ACTION_WEIGHTS["fileshare"])
    label_mults = _LABEL_WEIGHT_MULTIPLIERS.get(label, {})

    actions = []
    weights = []
    for action, w in base.items():
        if action == "share" and not allow_share:
            continue
        if action == "delete" and not allow_delete:
            continue
        # Apply label multiplier
        mult = label_mults.get(action, 1.0)
        actions.append(action)
        weights.append(w * mult)

    return actions, weights


def _pick_marginal_action(
    rng: random.Random,
    system: str,
    label: str,
    allow_share: bool,
    allow_delete: bool,
    baseline_weights: Optional[Dict[str, float]] = None,
) -> str:
    """Pick an action from the marginal distribution (first event in session)."""
    if baseline_weights:
        actions = list(baseline_weights.keys())
        weights = [float(baseline_weights[a]) for a in actions]
        if not allow_share and "share" in actions:
            idx = actions.index("share")
            actions.pop(idx)
            weights.pop(idx)
        if not allow_delete and "delete" in actions:
            idx = actions.index("delete")
            actions.pop(idx)
            weights.pop(idx)
        if actions:
            return rng.choices(actions, weights=weights, k=1)[0]

    actions, weights = _get_action_weights(system, label, allow_share, allow_delete)
    if not actions:
        return "read"
    return rng.choices(actions, weights=weights, k=1)[0]


def _pick_markov_action(
    rng: random.Random,
    prev_action: str,
    system: str,
    label: str,
    allow_share: bool,
    allow_delete: bool,
) -> Optional[str]:
    """Pick next action using Markov transition from previous action.

    Returns None if the session should end (e.g., after delete).
    """
    if prev_action == "delete":
        return None  # Session ends after delete

    transitions = _MARKOV_TRANSITIONS.get(prev_action)
    if not transitions:
        return None

    # Apply system and label conditioning to transition weights
    label_mults = _LABEL_WEIGHT_MULTIPLIERS.get(label, {})
    actions = []
    weights = []
    for action, w in transitions.items():
        if action == "share" and not allow_share:
            continue
        if action == "delete" and not allow_delete:
            continue
        mult = label_mults.get(action, 1.0)
        actions.append(action)
        weights.append(w * mult)

    if not actions:
        return None
    return rng.choices(actions, weights=weights, k=1)[0]


# ---------------------------------------------------------------------------
# File selection with label conditioning
# ---------------------------------------------------------------------------

def _compute_file_weights(
    files: List[Dict[str, Any]],
    base_weights: List[float],
    person_dept: str,
) -> List[float]:
    """Compute file selection weights conditioned on person's department.

    People in Finance/Legal/HR see more business files;
    people in Engineering/IT see fewer.
    """
    dept_lower = person_dept.lower().strip()
    if dept_lower in _HIGH_BUSINESS_DEPTS:
        business_boost = 3.0
    elif dept_lower in _LOW_BUSINESS_DEPTS:
        business_boost = 0.3
    else:
        business_boost = 1.0

    adjusted = []
    for i, f in enumerate(files):
        w = base_weights[i] if i < len(base_weights) else 0.001
        file_type = (f.get("type") or "regular").lower()
        if file_type == "business":
            w *= business_boost
        adjusted.append(w)

    return adjusted


